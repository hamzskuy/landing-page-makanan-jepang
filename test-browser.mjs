import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1366,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174',{waitUntil:'networkidle',timeout:90000});
await page.screenshot({path:'preview-desktop.png'});
console.log('Title:',await page.title());
await page.locator('#menu').scrollIntoViewIfNeeded();
await page.getByRole('button',{name:'Matcha & Drinks',exact:true}).click();
console.log('Drinks filter:',await page.locator('.food-card').count());
await page.getByRole('button',{name:'All',exact:true}).click();
console.log('All filter:',await page.locator('.food-card').count());
await page.getByRole('button',{name:'Perbesar The art of a good bowl'}).click();
console.log('Lightbox:',await page.locator('dialog').evaluate(el=>el.open));
await page.keyboard.press('ArrowRight');
console.log('Lightbox next:',await page.locator('.lightbox-footer p').textContent());
await page.keyboard.press('Escape');
console.log('Lightbox closed:',await page.locator('dialog').evaluate(el=>!el.open));
await page.locator('#signature').scrollIntoViewIfNeeded();
await page.mouse.move(0,0);
const initial=await page.locator('.carousel-bottom>span').textContent();
await page.waitForFunction(value=>document.querySelector('.carousel-bottom>span').textContent!==value,initial,{timeout:6500});
console.log('Autoplay: passed');
for(const width of [1920,1366,768,390,360]){await page.setViewportSize({width,height:900});await page.locator('#menu').scrollIntoViewIfNeeded();console.log('Responsive',width,await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,cards:getComputedStyle(document.querySelector('.menu-grid')).gridTemplateColumns})));}
await page.evaluate(()=>window.scrollTo(0,0));
await page.getByRole('button',{name:'Buka menu',exact:true}).click();
