await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'preview-mobile.png',fullPage:true});
console.log('Images:',await page.locator('img').evaluateAll(imgs=>imgs.map(i=>({alt:i.alt,loaded:i.complete&&i.naturalWidth>0,url:i.src}))));
console.log('Fallbacks:',await page.locator('.photo-fallback').allTextContents());
console.log('JS errors:',errors);
